namespace PayCalcDXPro.Data.Employee;

/// <summary>従業員情報から導出する値の計算（現行 F_従業員情報入力 の保存時ロジックを移植）。</summary>
public static class EmployeeCalc
{
    /// <summary>
    /// 源泉徴収税額表の「扶養親族等の数」を算出する。
    /// 本人の障害/寡婦夫/勤労学生、配偶者（合計所得見積×配偶者区分×配偶者障害者）、
    /// および扶養親族数・各障害・特定親族数を加算する。現行ロジックと一致。
    /// </summary>
    public static int 源泉扶養親族数(Employee e)
    {
        int n = 0;

        if (e.本人障害者 is "2" or "3") n++;        // 一般/特別の障害者
        if (e.本人寡婦夫 is "2" or "3") n++;         // 寡婦/ひとり親
        if (e.本人勤労学生 == "2") n++;              // 勤労学生

        // 配偶者区分（2=源泉控除対象/3=同一生計）で、合計所得見積が1（900万円以下）の場合に＋1
        if (e.配偶者合計所得見積 == "1" && e.配偶者区分 is "2" or "3") n++;

        // 配偶者区分が2（源泉控除対象）または3（同一生計）の場合の配偶者障害者加算（所得見積によらない）
        if (e.配偶者区分 is "2" or "3")
        {
            if (e.配偶者障害者 is "2" or "3") n += 1;      // 一般/特別
            else if (e.配偶者障害者 == "4") n += 2;        // 同居特別
        }

        n += e.扶養親族親族数 + e.扶養親族一般障害 + e.扶養親族特別障害 + e.扶養親族同居特別 + e.特定親族数;
        return n;
    }
}
